export function buildAugustDiaryData(selection: AugustSelection): AugustDiaryData {
  const storeEntries = selection.storeCandidates.length === 1
    ? soloStoreEntry(selection.storeCandidates[0], selection.storeChoices)
    : selection.storeCandidates.length > 1
      ? groupStoreEntry(selection.storeCandidates, selection.storeChoices)
      : ['今天下午便利店倒是沒有熟人特地來找我。客人一個接一個，收銀、補貨、整理架子，忙起來也沒什麼空閒。只是偶爾聽見門口的感應鈴，還是會下意識抬頭看一下。']

  const title = selection.eveningRoute === 'fried' ? '今天的炸雞有點不一樣' : '原來諺明哥也會這樣打鼓'
  const opening = [
    '回到家才發現，今天的制服口袋裡還有一張揉皺的收據。八月的天氣真的很誇張，下午在便利店裡吹著冷氣，走出門還是熱得像剛從蒸籠裡出來。',
    '本來以為今天就是普通的打工日，沒想到下班以後還有一段意外的行程。現在坐下來想想，倒覺得這一天過得滿值得記下來的。',
  ]
  const evening = eveningEntry(selection)
  const ending = [
    '寫到這裡才發現，今天其實沒有什麼驚天動地的大事。只是有人在我忙的時候留下來幫了一把，有人記得我喜歡的口味，也有人把一句很普通的叮嚀說得讓人一直記到現在。',
    '我本來以為夏天就是很熱、很黏、每天都想快點下班。結果偶爾也會有這種時候，明明只是很普通的一天，回家後卻還想多寫幾行。',
    '八月才剛開始，日記倒是已經有東西可以寫了。先這樣，明天還要早起，晚安！',
  ]

  return {
    version: 1,
    title,
    text: [...opening, ...storeEntries, ...evening, ...ending].join('\\n\\n'),
  }
}
