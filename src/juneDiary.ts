import type { JuneStudyCharacter } from './JuneStudyStory'

export type JuneDiaryCharacter = JuneStudyCharacter
export type JuneDiarySelection = {
  studyCharacter: JuneStudyCharacter
  studyChoices: number[]
  chatCharacter: JuneDiaryCharacter
  chatChoices: number[]
}
export type JuneDiaryData = {
  title: string
  text: string
}

const choiceAt = (choices: number[], index: number) =>
  Number.isInteger(choices[index]) && choices[index] >= 0 && choices[index] <= 2 ? choices[index] : 1

function studyEntry(character: JuneStudyCharacter, choices: number[]): string[] {
  const endingChoice = choiceAt(choices, 4)

  switch (character) {
    case 'wen':
      return [
        '今天的社會學理論報告總算有點眉目了。溫尚翊一看到我那一大疊參考書，第一句就問我是不是來搬家的。我明明是來求救的，他還有空先笑我，真的很欠揍。',
        '他沒有像老師那樣從頭到尾講一堆理論，反而叫我先把自己想說的東西講出來。後來他拿鉛筆把我草稿裡繞來繞去的句子劃掉，嘴上嫌我寫得太複雜，倒是一下就把我卡了三天的地方理順了。這個人腦袋到底是怎麼長的？',
        '中間一支筆沿著桌面滾到我們中間，我和他幾乎同時伸手。指尖碰到的時候，兩個人都停了一下。他先鬆開手，裝得一副沒事的樣子叫我拿去。明明就一支筆，我居然記到現在。',
        '更丟臉的是，後來我看他看得有點出神，居然被本人抓包。他問我看夠了沒，我當然立刻否認啊！可是他認真看資料的樣子確實……算了，不寫了，免得日記也被他看到。',
        endingChoice === 0
          ? '收東西的時候，我問他下次還能不能找他一起討論。他答得很快，還叫我下次先講，不要每次都臨時出現。講得好像很勉強，明明剛剛幫我看報告的時候也沒少講。'
          : endingChoice === 1
            ? '我還故意叫他溫老師，結果他立刻挑眉問我：「妳要不要聽聽看自己在講什麼？」這人真的很難逗，不過最後還是答應一起去吃東西了，哼。'
            : '我說今天腦細胞都快死光了，他居然叫我不要講得那麼誇張，還順手把快掉出包包的資料夾推回去。嘴巴很壞，手倒是挺忙的。',
      ]
    case 'ashin':
      return [
        '今天和阿信約好去咖啡廳各做各的事。我本來還想說這次總算可以安安靜靜讀完報告，結果安靜是安靜了，問題是對面那個人根本沒有一直在做正事。',
        '我一抬頭就看到他的筆記本上畫滿了奇奇怪怪的小人。有的抱著書哭，有的躺在地上裝死，還有一個腦袋大得很誇張，表情像是剛被期末考判了死刑。我真的差點在咖啡廳笑出聲。',
        '他一開始還想把本子藏起來，後來乾脆一頁一頁翻給我看，還很認真地介紹每個小人到底在幹嘛。結果我們兩個就這樣從自習變成了小人展覽，桌上還多了幾張隨手畫的紙。',
        '最可惡的是，他居然把我也畫進去了：抱著一大疊書，頭髮還翹起來，一看就知道是在笑我。可是最後那張小紙片他折得整整齊齊，偷偷夾進我的筆記本，旁邊還寫了「期末考加油」。這種小把戲真的很犯規。',
        endingChoice === 0
          ? '我問他這是不是特地畫給我的，他居然很自然地說是，因為看我今天很累，想讓我笑一下。還叫我不要弄丟。好啦，我才不會弄丟咧。'
          : endingChoice === 1
            ? '我問他可不可以把那張小紙片貼在筆記本上，他說這樣每次打開都會看到。嗯……這樣好像真的不錯，明天就找膠帶把它貼好。'
            : '我一時嘴快笑他畫得很醜，他還真的伸手想拿回去。當然不可能還他！最後他還是把紙片留給我了，嘴上說我很過分，自己卻一直在笑。',
      ]
    case 'masa':
      return [
        '今天跑去咖啡廳當瑪莎的臨時歷史老師。七月的期末考越來越近，他嘴上一直嫌課本和講義很煩，東西倒是帶得挺齊全。只是翻開一看，進度實在讓人有點想嘆氣。',
        '我在空白紙上幫他畫時間線，把前後發生的事情連起來。他一開始還在旁邊轉筆，後來終於把椅子挪近，盯著我的筆尖看，還會自己拿筆照著畫一遍。看他總算有認真起來，我突然有種老師看到學生開竅的感動。',
        '考他的時候，前兩題還算順利，第三題又把年份弄反。他明明心虛得要命，嘴上還說自己的記性比較有個性。到底誰會這樣形容自己的記性啦！不過他最後還是乖乖把錯題圈起來重寫了。',
        '中間我把橡皮擦推給他，他接過去時手指碰到我的手背，停了一下才低頭繼續寫。後來他忽然說，妳講的他比較記得住。這句話害我差點不知道怎麼接，只好假裝自己還在檢查他的筆記。',
        endingChoice === 0
          ? '收東西時我又逗他是不是離不開我了。他嘴上叫我少臭美，卻還是說考前有空的話再陪他讀一下。好啦，看在他今天有乖乖寫筆記的份上。'
          : endingChoice === 1
            ? '我說等考完要請他吃好吃的，結果他叫我先不要急著安排慶功宴。也是啦，先讓他把七月的考試過了再說。'
            : '最後我提醒他回去要認真一點，他也反過來叫我好好準備自己的期末考。明明是我在教他，怎麼最後變成互相監督了？',
      ]
    case 'stone':
      return [
        '今天和石頭在咖啡廳讀書。他早就把參考書和筆記整理好了，還把不懂的地方一個個圈起來，紙張邊角都對得整整齊齊。明明是我來幫他看功課，他還一直怕麻煩到我。',
        '我把自己的筆記挪到中間，陪他把幾個容易弄混的概念重新理了一遍。他聽得很認真，偶爾低頭記下來，遇到不確定的地方就停下來想一會兒，再用自己的話重新寫一次。比起急著把答案抄下來，他好像更在意自己是不是真的弄懂了。',
        '看到他寫到一半又皺起眉頭，我才發現他其實很擔心七月的期末考。剩下的時間不多，他怕自己記不牢。我跟他說不會的地方慢慢補就好，他才終於鬆了一點眉頭。',
        '後來他手指沾了好多鉛筆灰，自己還沒發現。我提醒他，他就把手掌翻過來給我看，笑得有點不好意思。那個畫面很普通，可是他看著我的時候，真的會讓人不自覺也跟著放輕聲音。',
        endingChoice === 0
          ? '分開前他問我，考前還能不能再約一起讀書。我答應了，還叫他不准熬夜。他笑著說好，眼睛卻一直看著我。希望他真的有聽進去。'
          : endingChoice === 1
            ? '我提議下次換個地方讀書，他說好，還說下次由他來找地方。這樣也不錯，感覺我們好像真的有了下一次的約定。'
            : '我叫他先把今天的內容複習好再說，他也沒有反駁，只提醒我別忘了準備自己的期末考。大家都在考試，誰也別想偷懶。',
      ]
    case 'yanming':
      return [
        '今天沒有去咖啡廳，而是跑到練團室找諺明哥借個安靜的地方看書。下午剛好沒有人預約，他在櫃檯後面整理預約簿和收據，看到我來，就先把裡面的桌子收出一個位置。',
        '我們真的就是各忙各的。我低頭看講義，他在櫃檯核對帳目，偶爾按幾下計算器，偶爾翻一下預約簿。中間他還順手替我倒了杯水，放下來時特地挪開我的講義，怕水杯碰倒。這種小地方他總是注意得到。',
        '後來電話響了，他起身去確認預約時間和器材需求，語氣跟平常聊天時不太一樣，做事俐落得很。我看得有點出神，被他發現後還問我怎麼了。原來一個人認真工作起來，真的會有另一種樣子。',
        '下午熱得要命，我讀到眼睛都快睜不開，差點直接趴在書上。他沒有催我，只把電風扇轉開一點，還拉了旁邊的椅子坐下來陪我休息五分鐘。練團室裡只有風扇和翻紙的聲音，意外地讓人很安心。',
        endingChoice === 0
          ? '走之前我說這裡根本是我的秘密基地，他笑著說下次先打電話，他幫我留個位置。欸，這樣講得好像真的可以常常來一樣。'
          : endingChoice === 1
            ? '我跟他說有人陪著的感覺不一樣，他只笑著說不客氣，還誇我今天也很認真。明明沒有講什麼特別的話，心情卻變好了。'
            : '我說等考完再來玩，他叫我先把期末考處理好。臨走還提醒我別忘了水杯，真的很像會把所有小事都記得的人。',
      ]
  }
}

function chatEntry(character: JuneStudyCharacter, choices: number[]): string[] {
  const first = choiceAt(choices, 0)
  const last = choiceAt(choices, 4)

  switch (character) {
    case 'wen':
      return [
        '晚上回到家，我又拿起手機找怪獸聊天。本來只是想跟他說早上買早餐時差點把豆漿灑出來，結果三言兩語就被他問出一堆細節。',
        first === 0
          ? '他照例先吐槽我到底拿了多少東西，還提醒我下次不要什麼都塞在同一隻手上。嘴巴真的很不饒人，可是這種熟悉的鬥嘴反而讓人覺得很放鬆。'
          : first === 1
            ? '我跟他說當時真的嚇了一跳，旁邊的人還看了我一眼。他倒覺得沒什麼，說東西掉了撿起來就好，根本沒人會記得。講得倒是挺有道理。'
            : '我乾脆宣布以後早餐只買固體食物，他回我一句「妳乾脆不要吃比較快」。真是的，跟他聊天怎麼連早餐都能吵起來。',
        last === 0
          ? '最後我們還聊到冰。我說也想吃，可是懶得出門，他叫我想吃就去買，不要為了一支冰淇淋想半天。這個人對別人的行動力倒是很有要求。'
          : last === 1
            ? '聊到晚餐後，我還在認真考慮要不要下樓買冰，他說我走到樓下都已經買回來了。好像也是……但考慮一下又不犯法吧！'
            : '我說要喝白開水欺騙自己，他居然回我很會省錢。這算稱讚嗎？我先當作是好了。',
      ]
    case 'ashin':
      return [
        '晚上回到家，我又找阿信聊了一會兒。開頭只是跟他說今天看到一朵雲，長得像一隻正在睡覺的兔子。沒想到這種小事也能讓我們聊上好一會兒。',
        first === 0
          ? '我跟他描述那朵雲有多像兔子，他居然認真問牠是怎麼睡的。明明只是一朵雲，卻被我們聊得好像真的有一隻兔子躺在天上。'
          : first === 1
            ? '我說自己盯著雲看太久，差點忘記要去哪裡。他沒有笑我，反而說每天趕來趕去，很少有時間注意這些東西。這句話聽起來還滿有道理的。'
            : '我堅持那朵雲一定是兔子變的，他還順著我的話問牠會不會掉下來。跟阿信聊天就是這樣，明明很無聊的事情也能越講越認真。',
        last === 0
          ? '最後聊到今天那些小小的開心事，他說有時候不用發生什麼大事，吃到喜歡的東西、看到好笑的畫面，就足夠讓一天變得不錯。'
          : last === 1
            ? '我說以後要多注意生活裡的小事情，他說那像是在替每天收集小禮物。這個比喻有點可愛，我決定先收下。'
            : '我說要寫一本開心事件大全，他居然問可不可以幫我畫封面。這種事他倒是很積極，明明一開始還說要認真做作業。',
      ]
    case 'masa':
      return [
        '晚上回到家，我突然想到小時候的事，就傳訊息去鬧瑪莎。結果一下子又聊到分零食、搶自己喜歡的東西，連誰比較幼稚都能爭半天。',
        first === 0
          ? '我說他小時候很小氣，他立刻追問我哪來的結論，還不肯承認。這個人真的從小到大都很會替自己辯護。'
          : first === 1
            ? '我們聊到以前分零食的事，他居然還記得我會把不好吃的推給他。怎麼連這種小事都記得啦！'
            : '我說他小時候就很欠揍，他馬上問我到底是來聊天還是來找架吵。嗯，目的可能都有一點。',
        last === 0
          ? '最重要的是，我最後還是逼他叫了一聲姐姐。雖然他叫完立刻嫌我很煩，但那聲「姐姐」我決定先記在帳上，之後還可以拿出來笑他。'
          : last === 1
            ? '我本來想讓他先叫姐姐，再考慮請他吃東西，結果他根本不上當，還說我很會談條件。哼，這次算他反應快。'
            : '我說不叫就算了，我去找別人玩，他反而叫我不要幼稚。明明自己也很幼稚，還敢說我。',
      ]
    case 'stone':
      return [
        '晚上回到家，我想起回來路上看到的那隻小貓，就傳訊息跟石頭分享。明明只是路上遇到的小傢伙，回想起來還是覺得很可愛。',
        first === 0
          ? '我把牠的樣子仔細描述給石頭聽，他還問牠有沒有讓我摸。連這種小事他都會先替小貓想，真的很細心。'
          : first === 1
            ? '我說牠一直蹲在路邊看我，感覺像在等吃的。石頭倒提醒我，說不定牠只是剛好在休息，還猜我是不是很想把牠帶回家。被他猜中了。'
            : '我說那隻貓一定是附近的老大，石頭居然還叫我下次經過記得跟老大打招呼。好啦，下次看到牠我要禮貌一點。',
        last === 0
          ? '聊到最後，我跟他說今天跟他聊天也很開心。他說有時候聊些小事，心情就會輕鬆一點。嗯，真的有這種感覺。'
          : last === 1
            ? '我說還有好多事情想跟他講，改天再慢慢聊。他回我不急，想到什麼再傳就好。這種不催人的語氣，聽了就很舒服。'
            : '我最後說要去睡了，他還提醒我早點休息、記得設鬧鐘。突然覺得明天早上好像真的不能賴床。',
      ]
    case 'yanming':
      return [
        '晚上回到家，我又找諺明哥聊了幾句。本來只是想跟他分享今天做飯時鬧出的笑話，結果連自己到底有沒有資格說會煮飯都被他拿來吐槽。',
        first === 0
          ? '我跟他說那碗麵吃起來像在嚼白開水，他問我到底是在煮麵還是在煮一碗熱水。明明是很正經的人，吐槽起來也挺準的。'
          : first === 1
            ? '我說自己本來還覺得很會煮飯，他倒是沒有真的笑我，只說只是少放了一樣東西，下次記得就好。被他這樣一講，好像也沒那麼丟臉了。'
            : '我宣布以後都吃泡麵，他提醒我泡麵也是要放調味包的。好吧，這個漏洞確實被他抓到了。',
        last === 0
          ? '最後我說跟他聊天很放鬆，謝謝他聽我講這些小事。他回我說那就好，還提醒我有空也要好好照顧自己。'
          : last === 1
            ? '我說還有好多蠢事可以分享，他說有空就聽我慢慢講，不過希望下次是比較不蠢的事情。這句倒是很有諺明哥的風格。'
            : '我說要去睡了，他提醒我早點休息，明天記得先吃早餐。好啦，今天真的有點晚了。',
      ]
  }
}

export function buildJuneDiaryData(selection: JuneDiarySelection): JuneDiaryData {
  const paragraphs = [
    '六月十五日，星期日。今天熱得我真的很想把自己塞進冰箱。五月十日之後一眨眼就到了六月中旬，期末報告也終於追到眼前。最近每天抱著講義跑來跑去，連去買個東西都恨不得把參考書一起帶上，今天總算逼自己坐下來好好處理了。',
    ...studyEntry(selection.studyCharacter, selection.studyChoices),
    ...chatEntry(selection.chatCharacter, selection.chatChoices),
    '寫到這裡才發現，今天其實沒有發生什麼驚天動地的大事。白天為了報告和考試忙得團團轉，晚上卻因為一朵雲、一隻貓、一碗忘了放鹽的麵，或是一句很普通的回覆，心情又慢慢好了起來。',
    '最近好像真的長大了一點點，開始要面對報告、考試，還有一堆不知道什麼時候才會做完的事情。不過也還好，生活裡還是有很多奇奇怪怪的小事可以記下來。',
    '啊，對了，明天一定要記得繼續寫報告。今天先到這裡，不然又要拖到半夜了。晚安！',
  ]
  return {
    title: '今天還挺值得記一下的。',
    text: paragraphs.join('\\n\\n'),
  }
}
