type Block = { kind: 'narration' | 'dialogue'; text: string; speaker?: string }
type Choice = { text: string; response: Block[]; affection: number }
type Round = { title: string; blocks: Block[]; choices: [Choice, Choice, Choice] }
type Route = {
  name: string
  subtitle: string
  location: string
  intro: Block[]
  rounds: [Round, Round, Round, Round, Round]
  ending: Block[]
}
type Phase = 'intro' | 'picker' | 'interaction' | 'complete'
type Progress = {
  phase: Phase
  character: JuneStudyCharacter | null
  roundIndex: number
  pendingChoice: number | null
  choices: number[]
}

const STORAGE_KEY = 'mayday-june-study-progress-v1'
const ORDER: JuneStudyCharacter[] = ['wen', 'ashin', 'masa', 'stone', 'yanming']
const initialProgress: Progress = {
  phase: 'intro',
  character: null,
  roundIndex: 0,
  pendingChoice: null,
  choices: [],
}

const n = (text: string): Block => ({ kind: 'narration', text })
const d = (speaker: string, text: string): Block => ({ kind: 'dialogue', speaker, text })
const c = (text: string, affection: number, response: Block[]): Choice => ({ text, affection, response })
const r = (title: string, blocks: Block[], choices: [Choice, Choice, Choice]): Round => ({ title, blocks, choices })

function isCharacter(value: unknown): value is JuneStudyCharacter {
  return typeof value === 'string' && ORDER.includes(value as JuneStudyCharacter)
}

function readProgress(): Progress {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? 'null') as Partial<Progress> | null
    if (!saved || !['intro', 'picker', 'interaction', 'complete'].includes(saved.phase ?? '')) return initialProgress
    const character = isCharacter(saved.character) ? saved.character : null
    const roundIndex = Number.isInteger(saved.roundIndex) ? Math.max(0, Math.min(4, Number(saved.roundIndex))) : 0
    const pendingChoice = Number.isInteger(saved.pendingChoice) && Number(saved.pendingChoice) >= 0 && Number(saved.pendingChoice) <= 2
      ? Number(saved.pendingChoice) : null
    const choices = Array.isArray(saved.choices)
      ? saved.choices.filter((value): value is number => Number.isInteger(value) && value >= 0 && value <= 2).slice(0, 5)
      : []
    const phase = saved.phase as Phase
    if ((phase === 'interaction' || phase === 'complete') && !character) return initialProgress
    return { phase, character, roundIndex, pendingChoice, choices }
  } catch {
    return initialProgress
  }
}

function clockForProgress(progress: Progress) {
  if (progress.phase === 'intro') return '13:30'
  if (progress.phase === 'picker') return '13:45'
  if (progress.phase === 'interaction') return ['14:00', '14:35', '15:10', '15:45', '16:20'][progress.roundIndex]
  return '17:10'
}

