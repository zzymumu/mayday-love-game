function Blocks({ blocks }: { blocks: Block[] }) {
  return (
    <div className="narrative-blocks">
      {blocks.map((block, index) => block.kind === 'dialogue' ? (
        <div className="narrative-dialogue" key={index}>
          <span>{block.speaker}</span>
          <p>{'「' + block.text.replace(/^「|」$/g, '') + '」'}</p>
        </div>
      ) : (
        <p className="narrative-paragraph" key={index}>{block.text}</p>
      ))}
    </div>
  )
}

export function JuneStudyStory({
  onAddAffection,
  onClockChange,
  onFinish,
}: {
  onAddAffection: (character: JuneStudyCharacter, amount: number) => void
  onClockChange: (time: string) => void
  onFinish: (selection: JuneStudySelection) => void
}) {
  const [progress, setProgress] = useState<Progress>(readProgress)
  const choiceLocked = useRef(false)

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(progress))
    onClockChange(clockForProgress(progress))
  }, [progress, onClockChange])

  const chooseCharacter = (character: JuneStudyCharacter) => {
    if (progress.phase !== 'picker') return
    setProgress({ phase: 'interaction', character, roundIndex: 0, pendingChoice: null, choices: [] })
  }

  const chooseChoice = (choiceIndex: number) => {
    if (!progress.character || progress.phase !== 'interaction' || progress.pendingChoice !== null || choiceLocked.current) return
    const currentRound = routes[progress.character].rounds[progress.roundIndex]
    const selected = currentRound?.choices[choiceIndex]
    if (!selected) return
    choiceLocked.current = true
    onAddAffection(progress.character, selected.affection)
    setProgress((current) => ({
      ...current,
      pendingChoice: choiceIndex,
      choices: [...current.choices, choiceIndex],
    }))
  }

  const continueRound = () => {
    if (progress.pendingChoice === null) return
    choiceLocked.current = false
    if (progress.roundIndex < 4) {
      setProgress((current) => ({ ...current, roundIndex: current.roundIndex + 1, pendingChoice: null }))
    } else {
      setProgress((current) => ({ ...current, phase: 'complete', pendingChoice: null }))
    }
  }

  const finish = () => {
    if (!progress.character || progress.choices.length !== 5 || progress.phase !== 'complete') return
    onFinish({ character: progress.character, choices: [...progress.choices] })
  }

  const route = progress.character ? routes[progress.character] : null
  const currentRound = route?.rounds[progress.roundIndex]
  const selectedChoice = progress.pendingChoice !== null && currentRound ? currentRound.choices[progress.pendingChoice] : null

  return (
    <div className="story-screen-overlay">
      <div className="story-screen-head">
        <div className="chapter-mark">6 月</div>
        <div className="story-contact-title">
          <strong>期末復習</strong>
          <small>1997 年 6 月 15 日・星期日</small>
        </div>
        <span className="story-head-spacer" />
      </div>

      <div className="story-narrative-scroll">
        <div className="story-kicker">JUNE · FINAL EXAMS</div>

        {progress.phase === 'intro' && (
          <>
            <h2 className="story-scene-title">六月中旬・期末考前</h2>
            <Blocks blocks={transitionBlocks} />
            <div className="story-action-bar story-inline-action">
              <button className="story-primary-button" onClick={() => setProgress((current) => ({ ...current, phase: 'picker' }))}>
                選擇今天一起複習的人 <ChevronRight size={15} />
              </button>
            </div>
          </>
        )}

        {progress.phase === 'picker' && (
          <>
            <h2 className="story-scene-title">今天想找誰一起複習？</h2>
            <p className="narrative-paragraph">你把講義和參考書整理好，拿起手機，想了想今天要找誰一起度過這個下午。</p>
            <div className="choice-area">
              <div className="choice-heading">選擇一位陪你複習的人</div>
              {ORDER.map((character) => {
                const item = routes[character]
                return (
                  <button className="reply-choice spring-invite-person-choice" key={character} onClick={() => chooseCharacter(character)}>
                    <span className="spring-invite-person-copy">
                      <strong>{item.name}</strong>
                    </span>
                    <ChevronRight size={15} />
                  </button>
                )
              })}
            </div>
          </>
        )}

        {progress.phase === 'interaction' && route && currentRound && (
          <>
            <h2 className="story-scene-title">{route.name}・{currentRound.title}</h2>
            <div className="reunion-pause-note">第 {progress.roundIndex + 1}／5 輪</div>
            {progress.roundIndex === 0 && <Blocks blocks={route.intro} />}
            <Blocks blocks={currentRound.blocks} />
            {selectedChoice ? (
              <>
                <Blocks blocks={[d('你', selectedChoice.text)]} />
                <Blocks blocks={selectedChoice.response} />
                <div className="story-action-bar story-inline-action">
                  <button className="story-primary-button" onClick={continueRound}>
                    {progress.roundIndex < 4 ? '繼續複習' : '看看今天的結尾'} <ChevronRight size={15} />
                  </button>
                </div>
              </>
            ) : (
              <div className="choice-area">
                <div className="choice-heading">你想怎麼回應？</div>
                {currentRound.choices.map((choice, index) => (
                  <button className="reply-choice" key={index} onClick={() => chooseChoice(index)}>
                    <span>{choice.text}</span><ChevronRight size={15} />
                  </button>
                ))}
              </div>
            )}
          </>
        )}

        {progress.phase === 'complete' && route && (
          <>
            <h2 className="story-scene-title">1997 年 6 月 15 日・期末複習的午後</h2>
            <Blocks blocks={route.ending} />
            <div className="reunion-pause-note">今天的複習暫時告一段落。</div>
            <div className="story-action-bar story-inline-action">
              <button className="story-primary-button" onClick={finish}>
                結束今天 <ChevronRight size={15} />
              </button>
            </div>
          </>
        )}
      </div>
    </div>
  )
}
